#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const root = fileURLToPath(new URL('../', import.meta.url));
const source = 'extensions/sparkclaw/iscpworkbench/operations.json';
const raw = readFileSync(root + source, 'utf8');
const registry = JSON.parse(raw);
const names = new Set();
for (const row of registry) {
  if (names.has(row.name)) throw new Error(`duplicate operation ${row.name}`);
  names.add(row.name);
}
const code = `// Code generated by scripts/sync-iscp-operations.mjs; DO NOT EDIT.\npackage iscpworkbench\n\nconst (\n${registry.map(row => `\t${row.constant} = ${JSON.stringify(row.name)}`).join('\n')}\n)\n`;
const formatted = execFileSync('gofmt', { input: code, encoding: 'utf8' });
for (const [path, value] of [
  ['extensions/sparkclaw/iscpworkbench/operations_generated.go', formatted],
  ['extensions/sparkclaw/protocol/iscp-operations.json', raw],
]) {
  if (process.argv.includes('--check')) {
    if (readFileSync(root + path, 'utf8') !== value) throw new Error(`stale operation projection: ${path}`);
  } else writeFileSync(root + path, value);
}
